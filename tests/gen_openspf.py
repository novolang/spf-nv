#!/usr/bin/env python3
"""Generate tests/openspf_tests.nv from the OpenSPF test suite.

    python3 -I tests/gen_openspf.py rfc7208-tests.yml tests/openspf_tests.nv

The input is `test/rfc7208-tests.yml` of the pyspf repository, the
openspf.org test suite release 2014.04, at commit
4bf96ea63af4999663809bae9b5530bce25e6f16 (sha256
901f561a6e2b1c1590a40a61b1ac7601226fd7045a7aae591a4d25421358d6f9).

The output carries the cases as data, one section per list, and the
driver that answers the evaluation's questions from the zone of the
section.  The rules the driver applies are the suite's own header:

* An `SPF` entry is a `TXT` entry, unless the same name has a `TXT`
  entry, in which case it is ignored (the suite's "auto-magic
  duplication"); `TXT: NONE` is a name that exists with no TXT record.
* A `TIMEOUT` entry makes the lookups of a type that has no record at
  that name fail temporarily.
* A `CNAME` is followed, up to eight times, for every type.
"""
import sys
import yaml


def lit(s):
    """A Novo string literal for a byte string given as a Python str."""
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == '\\':
            out.append('\\\\')
        elif ch == '$':
            out.append('\\$')
        elif ch == '\t':
            out.append('\\t')
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append('\\x%02X' % (o & 255))
    return '"' + ''.join(out) + '"'


def flat(v):
    if isinstance(v, list):
        return ''.join(str(x) for x in v)
    return str(v)


def zone_lines(zone):
    lines = []
    for domain, recs in zone.items():
        has_txt = any(isinstance(r, dict) and 'TXT' in r for r in recs)
        for r in recs:
            if r == 'TIMEOUT':
                lines.append(('Z', domain, 'TIMEOUT', ''))
            elif 'TXT' in r:
                v = flat(r['TXT'])
                lines.append(('Z', domain, 'NONE' if v == 'NONE' else 'TXT', '' if v == 'NONE' else v))
            elif 'SPF' in r:
                if not has_txt:
                    lines.append(('Z', domain, 'TXT', flat(r['SPF'])))
            elif 'MX' in r:
                pref, host = r['MX']
                lines.append(('Z', domain, 'MX', '%s %s' % (pref, host)))
            else:
                (k, v), = r.items()
                lines.append(('Z', domain, k, flat(v)))
        if not recs:
            lines.append(('Z', domain, 'NONE', ''))
    return lines


DRIVER = r"""// openspf_tests.nv — the openspf.org test suite for RFC 7208, run through
// the step.
//
// GENERATED by tests/gen_openspf.py from `test/rfc7208-tests.yml` of the
// pyspf repository (the openspf.org suite, release 2014.04), at commit
// 4bf96ea63af4999663809bae9b5530bce25e6f16.  Do not edit it by hand.
//
// Each section has a zone, which is a list of records, and cases, which
// are SPF checks.  The driver below plays the part of the resolver: it
// answers the evaluation's questions from the zone, one at a time, with
// the rules the suite's header gives (the generator's docstring lists
// them).

use std.test
use spfeval

struct Rec
    name: Str
    kind: Str
    value: Str

fn zone_of(rows: [Str]) -> [Rec]
    var zone: [Rec] = []
    for row in rows
        let f = str.split(row, "\t")
        if f[0] == "Z"
            list.push(zone, Rec { name: str.lower(f[1]), kind: f[2], value: f[3] })
    zone

fn kind_name(t: SpfQType) -> Str
    spfeval.qtype_name(t)

fn follow(zone: [Rec], start: Str) -> Str
    var name = start
    for _ in 0..8
        var next = ""
        for r in zone
            if r.name == name and r.kind == "CNAME"
                next = str.lower(r.value)
        if next == ""
            return name
        name = next
    name

fn resolve(zone: [Rec], q: SpfQuestion) -> SpfAnswer
    let name = follow(zone, q.name)
    let want = kind_name(q.qtype)
    var present = false
    var timeout = false
    var values: [Str] = []
    for r in zone
        if r.name == name
            present = true
            if r.kind == "TIMEOUT"
                timeout = true
            elif r.kind == want
                list.push(values, r.value)
    if timeout and list.len(values) == 0
        return spfeval.temp_fail(q.qtype, q.name)
    if not present
        return spfeval.nxdomain(q.qtype, q.name)
    spfeval.answer(q.qtype, q.name, values)

fn run_case(zone: [Rec], req: SpfRequest) -> SpfVerdict
    var answers: [SpfAnswer] = []
    for _ in 0..500
        let out = spfeval.check_host(req, answers)
        if out.done
            return out.verdict
        list.push(answers, resolve(zone, out.question))
    test.fail("the check did not finish")
    spfeval.check_host(req, answers).verdict

// One case expects the nibbles of an IPv6 address in upper case, because the
// suite's reference implementation keeps the case of the address it was
// given.  RFC 7208 section 7.4 prints them in lower case, and so does
// this package, so that case alone is compared without regard to case.
fn same_text(name: Str, got: Str, want: Str) -> Bool
    if name == "v-macro-ip6"
        return str.lower(got) == str.lower(want)
    got == want

fn run_section(rows: [Str]) [io]
    let zone = zone_of(rows)
    var bad: [Str] = []
    for row in rows
        let f = str.split(row, "\t")
        if f[0] == "T"
            let v = run_case(zone, spfeval.request(f[3], f[4], f[2], "unknown", 1700000000))
            let got = spfeval.result_name(v.result)
            if not list.contains(str.split(f[5], ","), got)
                list.push(bad, "${f[1]}: got ${got} (${v.reason}), want ${f[5]}")
            elif f[6] != "\x01" and f[6] != "DEFAULT" and got == "fail" and not same_text(f[1], v.explanation, f[6])
                list.push(bad, "${f[1]}: explanation `${v.explanation}`, want `${f[6]}`")
    if list.len(bad) > 0
        test.fail(str.join(bad, "\n"))

"""


def main():
    src, dst = sys.argv[1], sys.argv[2]
    docs = list(yaml.safe_load_all(open(src, encoding='utf-8')))
    out = []
    out.append(DRIVER)
    names = []
    for i, d in enumerate(docs):
        rows = []
        for ln in zone_lines(d.get('zonedata') or {}):
            rows.append('\t'.join(ln))
        for name, t in d['tests'].items():
            res = t['result']
            res = ','.join(res) if isinstance(res, list) else res
            rows.append('\t'.join(['T', name, str(t['helo']), str(t['host']),
                                   str(t['mailfrom']), res, str(t.get('explanation', '\x01'))]))
        title = d['description']
        out.append('// ── %s %s\n' % (title, '─' * max(1, 72 - 6 - len(title) - 1)))
        out.append('const SECTION_%d = [' % i)
        out.append(',\n'.join('    ' + lit(r) for r in rows))
        out.append(']\n')
        out.append('@test\nfn test_openspf_%d_%s() [io]\n    test.case(%s)\n    run_section(SECTION_%d)\n'
                   % (i, ''.join(c if c.isalnum() else '_' for c in title.lower()), lit(title), i))
    open(dst, 'w').write('\n'.join(out))


main()
